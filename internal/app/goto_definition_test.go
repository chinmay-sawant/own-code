func TestGotoDefinitionAmbiguousJumpsToBest(t *testing.T) {
	app := newDiskGotoTestApp(t, gotoDiskFiles())
	ctx := context.Background()
	app.openFile("use2.go")
	enterEditAtFirstLine(t, app)
	placeCaretOnWord(t, app, "DupThing", 0)

	if err := app.gotoDefinitionAtCaret(ctx); err != nil {
		t.Fatal(err)
	}

	// Same path length sorts dup1.go before dup2.go; the generated file
	// never competes.
	if got := app.activeDocPath(); got != "dup1.go" {
		t.Fatalf("path = %q, want dup1.go", got)
	}

	line, _ := offsetLineCol(app.edit.Text(), app.editCaret)
	if line != 2 {
		t.Fatalf("caret line = %d, want 2", line)
	}

	toast := app.View().Toast
	if !toast.Show || !strings.Contains(toast.Message, "2 definitions") || !strings.Contains(toast.Message, "Ctrl+T") {
		t.Fatalf("toast = %+v, want a 2-definition count pointing at Ctrl+T", toast)
	}

	if !app.canNavBack() || app.navBackPath() != "use2.go" {
		t.Fatalf("nav back = %q, want use2.go", app.navBackPath())
	}
}

