func TestGotoDefinitionKeybinding(t *testing.T) {
	app := newTestApp(t)
	ctx := context.Background()
	app.openFile("backend/probe.go")
	enterEditAtFirstLine(t, app)
	placeCaretOnWord(t, app, "once", 0)

	// Ctrl+D must be the live chord and must not collide with another
	// default: the dev dock owns F12, not this.
	if got := app.keymapChord("goto-definition"); got != "Ctrl+D" {
		t.Fatalf("chord = %q, want Ctrl+D", got)
	}

	if got := resolveChord(app.settings.Keymap, "Ctrl+D"); len(got) != 1 || got[0] != "goto-definition" {
		t.Fatalf("Ctrl+D resolves to %v, want only goto-definition", got)
	}

	app.ctrl = true
	defer func() { app.ctrl = false }()

	if err := app.onKeyDown(ctx, "d"); err != nil {
		t.Fatal(err)
	}

	line, _ := offsetLineCol(app.edit.Text(), app.editCaret)
	if line != 134 || app.activeDocPath() != "backend/probe.go" {
		t.Fatalf("Ctrl+D jumped to %s:%d, want backend/probe.go:134", app.activeDocPath(), line)
	}
}

