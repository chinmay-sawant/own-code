func TestGotoDefinitionFallbackOpensSearch(t *testing.T) {
	app := newTestApp(t)
	ctx := context.Background()
	app.openFile("backend/probe.go")
	enterEditAtFirstLine(t, app)
	// "beacon" only appears in string/comment text, never as a symbol.
	placeCaretOnWord(t, app, "beacon", 0)

	if err := app.gotoDefinitionAtCaret(ctx); err != nil {
		t.Fatal(err)
	}

	toast := app.View().Toast
	if !toast.Show || toast.Title != "Go to definition" {
		t.Fatalf("toast = %+v, want a Go to definition note", toast)
	}

	if !strings.Contains(toast.Message, "Definition not found") || !strings.Contains(toast.Message, "textual matches") {
		t.Fatalf("fallback message = %q, want definition-not-found with a match count", toast.Message)
	}

	if !app.searchOpen || app.searchQuery != "beacon" {
		t.Fatalf("search open = %v query = %q, want open with beacon", app.searchOpen, app.searchQuery)
	}

	if got := app.activeDocPath(); got != "backend/probe.go" {
		t.Fatalf("fallback moved files to %q", got)
	}
}

