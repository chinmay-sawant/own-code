// placeCaretOnWord moves the edit caret inside the nth occurrence of word.
func placeCaretOnWord(t *testing.T, app *App, word string, occurrence int) {
	t.Helper()

	if app.edit == nil {
		t.Fatal("no edit buffer")
	}

	text := app.edit.Text()
	from := 0
	idx := -1

	for i := 0; i <= occurrence; i++ {
		j := strings.Index(text[from:], word)
		if j < 0 {
			t.Fatalf("word %q occurrence %d not found", word, occurrence)
		}

		idx = from + j
		from = idx + len(word)
	}

	app.editCaret = utf8.RuneCountInString(text[:idx]) + 1
	app.editAnchor = app.editCaret
	app.refresh()
}

// newDiskGotoTestApp builds an app over a temp dir of real files, so the
// symbol index, text search, and file reads all run against disk.
func newDiskGotoTestApp(t *testing.T, files map[string]string) *App {
	t.Helper()

	dir := t.TempDir()

	for name, content := range files {
		full := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	app, err := NewWithLimit(dir, 100)
	if err != nil {
		t.Fatalf("NewWithLimit: %v", err)
	}

	if err := app.Page().Redraw(context.Background()); err != nil {
		t.Fatalf("redraw: %v", err)
	}

	return app
}

func gotoDiskFiles() map[string]string {
	return map[string]string{
		"defs.go": "package main\n\ntype Widget struct{}\n\nfunc NewWidget() Widget {\n\treturn Widget{}\n}\n",
		"use.go":  "package main\n\nfunc Use() Widget {\n\treturn NewWidget()\n}\n",
		"dup1.go": "package main\n\nfunc DupThing() {}\n",
		"dup2.go": "package main\n\nfunc DupThing() {}\n",
		// Generated sources never win, even when the index knows them.
		"genmark.go": "// Code generated by tool. DO NOT EDIT.\npackage main\n\nfunc DupThing() {}\n",
		"use2.go":    "package main\n\nfunc CallDup() {\n\tDupThing()\n}\n",
		// The scanner prunes vendor, so this file exercises the skip rule
		// only when injected into the index (see the vendor test).
		"vendor/vv/widget.go": "package vv\n\ntype Widget struct{}\n",
	}
}

