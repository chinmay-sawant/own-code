func TestGotoSkipCandidate(t *testing.T) {
	app := newDiskGotoTestApp(t, gotoDiskFiles())
	app.ws.ByPath["dup2.go"].Ignored = true

	cases := []struct {
		path string
		want bool
	}{
		{"defs.go", false},
		{"dup1.go", false},
		{"dup2.go", true}, // gitignored
		{"vendor/vv/widget.go", true},
		{"node_modules/x/y.go", true},
		{"dist/app.js", true},
		{"genmark.go", true}, // "Code generated" header on disk
		{"cover.pb.go", true},
		{"mock.gen.go", true},
		{"img.png", true},
	}

	for _, tc := range cases {
		if got := gotoSkipCandidate(app.ws, tc.path); got != tc.want {
			t.Errorf("gotoSkipCandidate(%q) = %v, want %v", tc.path, got, tc.want)
		}
	}
}

